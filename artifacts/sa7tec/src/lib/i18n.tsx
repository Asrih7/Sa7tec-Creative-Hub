export type StringKey = keyof (typeof STRINGS)["en"];

const STORAGE_KEY = "sa7tec_lang";

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  dir: "ltr" | "rtl";
  t: (key: StringKey) => string;
  tr: (value: LocalizedString | undefined) => string;
};

const LanguageContext = createContext<Ctx | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window === "undefined") return "en";
    const stored = localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (stored && (stored === "en" || stored === "fr" || stored === "ar")) return stored;
    const browser = navigator.language.slice(0, 2).toLowerCase();
    if (browser === "fr") return "fr";
    if (browser === "ar") return "ar";
    return "en";
  });

  const dir = useMemo<"ltr" | "rtl">(() => (lang === "ar" ? "rtl" : "ltr"), [lang]);

  useEffect(() => {
    const html = document.documentElement;
    html.lang = lang;
    html.dir = dir;
    localStorage.setItem(STORAGE_KEY, lang);
  }, [lang, dir]);

  const setLang = useCallback((l: Lang) => setLangState(l), []);

  const t = useCallback(
    (key: StringKey): string => {
      const dict = STRINGS[lang] as Record<string, string>;
      return dict[key] ?? STRINGS.en[key] ?? key;
    },
    [lang],
  );

  const trBound = useCallback((value: LocalizedString | undefined) => tr(value, lang), [lang]);

  const value = useMemo(
    () => ({ lang, setLang, dir, t, tr: trBound }),
    [lang, setLang, dir, t, trBound],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx;
}
