export type LocalizedString = string | { en: string; fr?: string; ar?: string };

export function tr(value: LocalizedString | undefined | null, lang: Lang): string {
  if (value === undefined || value === null) return "";
  if (typeof value === "string") return value;
  return value[lang] || value.en || value.fr || value.ar || "";
}

export function toLocalized(value: LocalizedString | undefined): { en: string; fr: string; ar: string } {
  if (!value) return { en: "", fr: "", ar: "" };
  if (typeof value === "string") return { en: value, fr: "", ar: "" };
  return { en: value.en || "", fr: value.fr || "", ar: value.ar || "" };
}

